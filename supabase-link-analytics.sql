begin;

create table if not exists public.link_click_events (
  id bigint generated by default as identity primary key,
  link_id uuid not null references public.links(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  clicked_at timestamptz not null default now()
);

create index if not exists link_click_events_owner_date_idx
  on public.link_click_events (user_id, clicked_at);

alter table public.link_click_events enable row level security;

revoke all on public.link_click_events from public, anon, authenticated;
grant select on public.link_click_events to authenticated;

drop policy if exists "Analytics owners can read click events" on public.link_click_events;
create policy "Analytics owners can read click events"
  on public.link_click_events for select to authenticated
  using (user_id = (select auth.uid()));

-- Keep owner isolation even on projects with an older, broader read policy.
drop policy if exists "Analytics reads are restricted to the owner" on public.link_click_events;
create policy "Analytics reads are restricted to the owner"
  on public.link_click_events as restrictive for select to authenticated
  using (user_id = (select auth.uid()));

create or replace function public.increment_link_clicks(link_id uuid)
returns void
language sql
security definer
set search_path = ''
as $$
  with clicked_link as (
    update public.links as link
    set clicks = coalesce(link.clicks, 0) + 1
    where link.id = $1 and link.active
    returning link.id, link.user_id
  )
  insert into public.link_click_events (link_id, user_id, clicked_at)
  select id, user_id, now() from clicked_link;
$$;

revoke all on function public.increment_link_clicks(uuid) from public;
grant execute on function public.increment_link_clicks(uuid) to anon, authenticated;

commit;
